#!/usr/bin/env python3
"""Regenerates the embedded assets in assets/ from the sources in tools/source/.

    python3 tools/make-assets.py

Sources expected in tools/source/:
    Tinos-Regular.ttf      PDF body font (Times-metric compatible)
    Tinos-Bold.ttf
    IBMPlexSans-var.ttf    UI font (variable)
    IBMPlexMono-Regular.ttf
    IBMPlexMono-Medium.ttf

Signatures are deliberately not embedded: the app asks for one at runtime and
keeps it in the browser, so no signature is ever committed or published.
"""

import base64
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "source"
OUT = ROOT / "assets"

# Latin-1 + Latin Extended-A covers Hungarian and the rest of Western/Central Europe.
UNICODES = (
    "U+0020-007E,U+00A0-00FF,U+0100-017F,U+2010-2015,U+2018-201A,"
    "U+201C-201E,U+2020-2022,U+2026,U+2030,U+2039,U+203A,U+20AC,"
    "U+2122,U+00A9,U+00AE"
)


def subset(name: str) -> bytes:
    out = SRC / f"{name}.subset.ttf"
    subprocess.run(
        [
            "pyftsubset", str(SRC / f"{name}.ttf"),
            f"--unicodes={UNICODES}",
            "--layout-features=kern,liga,ccmp,locl,mark,mkmk",
            f"--output-file={out}",
            "--no-hinting",
        ],
        check=True,
    )
    return out.read_bytes()


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def main() -> int:
    OUT.mkdir(exist_ok=True)

    tinos_regular = b64(subset("Tinos-Regular"))
    tinos_bold = b64(subset("Tinos-Bold"))

    (OUT / "embedded.js").write_text(
        "// Generated by tools/make-assets.py — do not edit by hand.\n"
        "window.TIG_EMBEDDED = {\n"
        f'  fontRegular: "{tinos_regular}",\n'
        f'  fontBold: "{tinos_bold}"\n'
        "};\n",
        encoding="utf-8",
    )

    faces = [
        ("TIG Sans", "IBMPlexSans-var", "100 700", "normal"),
        ("TIG Mono", "IBMPlexMono-Regular", "400", "normal"),
        ("TIG Mono", "IBMPlexMono-Medium", "500", "normal"),
    ]
    css = ["/* Generated by tools/make-assets.py — do not edit by hand. */"]
    for family, name, weight, style in faces:
        data = b64(subset(name))
        css.append(
            "@font-face{\n"
            f"  font-family:'{family}';\n"
            f"  font-weight:{weight};\n"
            f"  font-style:{style};\n"
            "  font-display:block;\n"
            f"  src:url(data:font/ttf;base64,{data}) format('truetype');\n"
            "}"
        )
    (OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")

    for path in (OUT / "embedded.js", OUT / "fonts.css"):
        print(f"{path.relative_to(ROOT)}  {path.stat().st_size:,} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
